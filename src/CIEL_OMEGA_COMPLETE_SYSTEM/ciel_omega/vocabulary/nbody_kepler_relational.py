@dataclass(frozen=True)
class ConsentGeometry:
    admissible_projection_norm: Optional[float]
    residual_norm: Optional[float]
    alignment: Optional[float]
    status: str

def consent_geometry(actual_velocity: Sequence[float], admissible_basis: Optional[np.ndarray]) -> ConsentGeometry:
    v=np.asarray(actual_velocity,dtype=float).ravel()
    if admissible_basis is None:
        return ConsentGeometry(None,None,None,"UNKNOWN")
    B=np.asarray(admissible_basis,dtype=float)
    if B.ndim!=2 or B.shape[1]!=v.size:
        raise ValueError("admissible_basis shape")
    if B.shape[0]==0:
        proj=np.zeros_like(v)
    else:
        _,_,Vh=np.linalg.svd(B,full_matrices=False)
        rank=np.linalg.matrix_rank(B)
        Q=Vh[:rank].T
        proj=Q@(Q.T@v) if rank else np.zeros_like(v)
    residual=v-proj
    nv=float(np.linalg.norm(v))
    return ConsentGeometry(float(np.linalg.norm(proj)),float(np.linalg.norm(residual)),None if nv==0 else float(np.linalg.norm(proj)/nv),"DERIVED")

