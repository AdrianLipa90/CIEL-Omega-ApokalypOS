@dataclass(frozen=True)
class RelationalBody:
    body_id: str
    position: np.ndarray
    velocity: np.ndarray
    inertia: float = 1.0

    def __post_init__(self):
        x=np.asarray(self.position,dtype=float)
        v=np.asarray(self.velocity,dtype=float)
        if x.ndim != 1 or v.ndim != 1 or x.shape != v.shape:
            raise ValueError("position and velocity must be equal-shaped 1D vectors")
        if x.size < 2:
            raise ValueError("intrinsic dimension must be >= 2")
        if self.inertia <= 0:
            raise ValueError("inertia must be positive")
        object.__setattr__(self,"position",x)
        object.__setattr__(self,"velocity",v)

    @property
    def dim(self) -> int:
        return int(self.position.size)

@dataclass(frozen=True)
class PairCoupling:
    i: int
    j: int
    mu: float

    def __post_init__(self):
        if self.i == self.j:
            raise ValueError("self coupling invalid")
        if self.mu < 0:
            raise ValueError("mu must be nonnegative")

def unit_sphere_area(dim_minus_one: int) -> float:
    N = int(dim_minus_one) + 1
    if N < 2:
        raise ValueError("N must be >= 2")
    return float(2.0 * math.pi**(N/2.0) / math.gamma(N/2.0))

def pair_displacement(a: RelationalBody, b: RelationalBody) -> np.ndarray:
    if a.dim != b.dim:
        raise ValueError("dimension mismatch")
    return b.position-a.position

def pair_distance(a: RelationalBody, b: RelationalBody) -> float:
    return float(np.linalg.norm(pair_displacement(a,b)))

def nd_green_potential_from_r(r: float, mu: float, N: int, *, r0: Optional[float]=None) -> float:
    r=float(r); mu=float(mu); N=int(N)
    if r <= 0:
        raise ValueError("r must be positive")
    if N < 2:
        raise ValueError("N must be >= 2")
    if N == 2:
        if r0 is None:
            r0=1.0
        if r0 <= 0:
            raise ValueError("r0 must be positive")
        return float(mu*math.log(r/float(r0)))
    return float(-mu/((N-2)*(r**(N-2))))

def nd_green_potential(a: RelationalBody, b: RelationalBody, mu: float, *, r0: Optional[float]=None) -> float:
    if a.dim != b.dim:
        raise ValueError("dimension mismatch")
    return nd_green_potential_from_r(pair_distance(a,b),mu,a.dim,r0=r0)

def inverse_distance_potential(a: RelationalBody, b: RelationalBody, mu: float) -> float:
    """Backward-compatible API name; literally inverse-distance only for N=3."""
    return nd_green_potential(a,b,mu)

def central_pair_force(a: RelationalBody, b: RelationalBody, mu: float) -> np.ndarray:
    rvec=pair_displacement(a,b)
    r=float(np.linalg.norm(rvec))
    if r == 0:
        raise ZeroDivisionError("relational collision/singularity")
    return float(mu)*rvec/(r**a.dim)

def radial_flux_invariant(force_magnitude: float, r: float, N: int) -> float:
    if r <= 0 or N < 2:
        raise ValueError
    return float(force_magnitude*unit_sphere_area(N-1)*(r**(N-1)))

def accelerations(bodies: Sequence[RelationalBody], couplings: Sequence[PairCoupling]) -> Tuple[np.ndarray,...]:
    if not bodies:
        return tuple()
    N=bodies[0].dim
    if any(b.dim!=N for b in bodies):
        raise ValueError("all bodies must share intrinsic dimension")
    F=[np.zeros(N,dtype=float) for _ in bodies]
    for c in couplings:
        if not (0 <= c.i < len(bodies) and 0 <= c.j < len(bodies)):
            raise IndexError("coupling body index")
        f=central_pair_force(bodies[c.i],bodies[c.j],c.mu)
        F[c.i]+=f
        F[c.j]-=f
    return tuple(F[i]/bodies[i].inertia for i in range(len(bodies)))

def bivector_angular_momentum(body: RelationalBody) -> np.ndarray:
    x=body.position; v=body.velocity
    return body.inertia*(np.outer(x,v)-np.outer(v,x))

def total_bivector_angular_momentum(bodies: Sequence[RelationalBody]) -> np.ndarray:
    if not bodies:
        return np.zeros((0,0))
    N=bodies[0].dim
    return sum((bivector_angular_momentum(b) for b in bodies),start=np.zeros((N,N)))

def kinetic_energy(bodies: Sequence[RelationalBody]) -> float:
    return float(sum(0.5*b.inertia*np.dot(b.velocity,b.velocity) for b in bodies))

def potential_energy(bodies: Sequence[RelationalBody], couplings: Sequence[PairCoupling]) -> float:
    return float(sum(nd_green_potential(bodies[c.i],bodies[c.j],c.mu) for c in couplings))

def total_energy(bodies, couplings) -> float:
    return kinetic_energy(bodies)+potential_energy(bodies,couplings)

