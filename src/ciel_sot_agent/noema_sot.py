        print(f"  operating_mode   : {report['operating_mode']}")
        print(f"  priority_order   : {' > '.join(report['priority_order'])}")
        tm = report.get("tag_matrix", {})
        print(f"\ntag_matrix ({len(tm)} tagów):")
        for k, v in tm.items():
            print(f"  {k:35s}: {v}")
        fs = report.get("file_mass_summary", {})
        if fs:
            print("\nfile_mass_summary:")
            print(f"  total_files   : {fs.get('total_files')}")
            print(f"  mean_M_sem    : {fs.get('mean_M_sem')}")
